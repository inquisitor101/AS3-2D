  /*! @brief Verify every stored rule, including polynomial exactness. */
  [[nodiscard]] inline constexpr bool Validate(void)
  {
    for(std::size_t n=MinPoints; n<=MaxPoints; n++)
    {
      if( !NIntegrationRuleValidation::ValidateRule(ETypeQuadrature::GAUSS_LEGENDRE,
                                                    GetPoints(n), GetWeights(n)) )
        return false;
    }
    return true;
  }

